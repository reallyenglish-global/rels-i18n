require 'localeapp'
require 'yaml'
require 'json'
require 'digest/sha2'
require 'fileutils'


require_relative '../config/localeapp.rb'

JSON_EXT = '.json'
YAML_EXT = '.yml'

LOCAL = Dir.pwd
JSON_DATA_DIRECTORY = File.join(LOCAL, 'src/i18n/')
MASTER_JSON_PATH = File.join(JSON_DATA_DIRECTORY, 'master.json')
MASTER_YAML_PATH = File.join(__dir__, '../.tmp/', 'en.yml')
YAML_DATA_DIRECTORY = Localeapp.configuration.translation_data_directory

if !File.exists?(MASTER_JSON_PATH)
  puts "required file(s) missing:"
  exit 1
end


Localeapp.configure

JAML =
  Struct.new(:path) do
    def load
      @data = JSON.parse(File.read(path)) if ext == JSON_EXT
      @data = YAML.load(File.read(path)) if ext == YAML_EXT
      @data
    end

    def ext
      @ext ||= File.extname(path)
    end

    def data
      @data ||= load
    end

    def filename
      File.basename(path, ext)
    end

    def modified_at
      File.mtime(path)
    end

    def json
      JSON.pretty_generate(data)
    end

    def yaml
      output = data.to_yaml
      output.gsub!(/---\n/, '')
      output.gsub!(/^:/, '')

      output
    end

    def write(path)
      wants = File.extname(path)
      output = json if wants == JSON_EXT
      output = yaml if wants == YAML_EXT
      File.open(path, 'w') { |f| f.puts output }
      self
    end
  end

def master
  @master ||= JAML.new(MASTER_JSON_PATH)
end

def has_unpushed_changes?
  master.modified_at > Time.at(Localeapp.poller.updated_at || 0)
end

def transform_yaml_to_json
  Dir["#{YAML_DATA_DIRECTORY}/*.yml"].each do |src|
    jaml = JAML.new(src)
    dest = File.join(JSON_DATA_DIRECTORY, "#{jaml.filename}.json")
    jaml.write(dest)
  end
end

def pull
  must_pull = Localeapp.poller.updated_at < Time.now.to_i - 15_552_000
  puller = must_pull ? Localeapp::CLI::Pull.new : Localeapp::CLI::Update.new
  puller.execute

  transform_yaml_to_json
end

def push
  master.write(MASTER_YAML_PATH)
  pusher = Localeapp::CLI::Push.new
  pusher.execute(MASTER_YAML_PATH)
end

def bootstrap
  FileUtils.mkdir_p(YAML_DATA_DIRECTORY) unless Dir.exists?(YAML_DATA_DIRECTORY)
end

def write_manifest

  package = JSON.load_file(File.join(Dir.pwd, 'package.json'))
  locales = (Dir.each_child(JSON_DATA_DIRECTORY).to_a - ['master.json','index.js']).map { |file| File.basename(file, ".json") }

  output = "/*\n"
  output << "  Autogenerated by rels-i18n\n"
  output << "  Any changes you make will be overwritten on update.\n"
  output << "*/\n\n"
  output << "import RelsI18n from 'rels-i18n'\n"
  locales.each do |locale|
    output << "import #{locale.gsub('-', '')} from './#{locale}'\n"
  end
  output << "\n"
  locales.each do |locale|
    output << "RelsI18n.addLocaleData(#{locale.gsub('-', '')})\n"
  end
  output << "\n"

  helper = <<-i18n
 const i18n = {
  configure({ locale = 'en' }) {
    RelsI18n.setLocale(locale)
  },

  t(key, options) {
    return RelsI18n.t('#{package['name']}.' + key, options)
  },

  strftime(date, format) {
    return RelsI18n.strftime(date, format)
  },

  strftimeWithoutTimezone(date, format) {
    return RelsI18n.strftimeWithoutTimezone(date, format)
  },
}

export default i18n
i18n

  output << helper
  File.open(File.join(JSON_DATA_DIRECTORY, "index.js"), 'w') { |file|
    file.puts output
  }
end

bootstrap
push if has_unpushed_changes?
pull

write_manifest

exit 0
