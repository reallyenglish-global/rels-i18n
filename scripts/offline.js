#!/usr/bin/env node
'use strict'

const fs = require('fs')
const path = require('path')

const PROJECT_ROOT = process.cwd()
const I18N_DIR = path.join(PROJECT_ROOT, 'src', 'i18n')
const MASTER_PATH = path.join(I18N_DIR, 'master.json')
const INDEX_PATH = path.join(I18N_DIR, 'index.js')

const readJson = (filePath) => {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'))
  } catch (error) {
    throw new Error(`Invalid JSON in ${path.relative(PROJECT_ROOT, filePath)}: ${error.message}`)
  }
}

const localeIdentifier = (locale) => {
  const identifier = locale.replace(/[^A-Za-z0-9$]+(.)?/g, (_, next) =>
    next ? next.toUpperCase() : '',
  )
  if (!/^[A-Za-z_$]/.test(identifier)) return `locale_${identifier}`
  return identifier
}

const validateLocaleData = (filePath, expectedPackageName) => {
  const locale = path.basename(filePath, '.json')
  const data = readJson(filePath)
  const localeKeys = Object.keys(data)

  if (locale === 'master') return null
  if (localeKeys.length !== 1 || localeKeys[0] !== locale) {
    throw new Error(
      `${path.relative(
        PROJECT_ROOT,
        filePath,
      )} must contain exactly its filename locale key (${locale})`,
    )
  }
  if (!data[locale] || typeof data[locale] !== 'object' || Array.isArray(data[locale])) {
    throw new Error(`${path.relative(PROJECT_ROOT, filePath)} locale data must be an object`)
  }
  if (!Object.prototype.hasOwnProperty.call(data[locale], expectedPackageName)) {
    throw new Error(
      `${path.relative(
        PROJECT_ROOT,
        filePath,
      )} is missing package namespace ${expectedPackageName}`,
    )
  }

  return { locale, data }
}

const loadProject = () => {
  if (!fs.existsSync(MASTER_PATH)) {
    throw new Error(`rels-i18n requires ${path.relative(PROJECT_ROOT, MASTER_PATH)}`)
  }

  const packageJson = readJson(path.join(PROJECT_ROOT, 'package.json'))
  const master = readJson(MASTER_PATH)
  const packageName = packageJson.name

  if (!packageName) throw new Error('package.json must define a name')
  if (!master.en || typeof master.en !== 'object' || Array.isArray(master.en)) {
    throw new Error('master.json must contain a top-level en object')
  }
  if (!Object.prototype.hasOwnProperty.call(master.en, packageName)) {
    throw new Error(`master.json is missing package namespace ${packageName}`)
  }

  const files = fs
    .readdirSync(I18N_DIR)
    .filter((file) => file.endsWith('.json') && file !== 'master.json')
    .sort()
  const locales = files.map((file) => validateLocaleData(path.join(I18N_DIR, file), packageName))
  const identifiers = new Map()

  for (const { locale } of locales) {
    const identifier = localeIdentifier(locale)
    const previous = identifiers.get(identifier)
    if (previous)
      throw new Error(
        `locale identifiers collide: ${previous} and ${locale} both map to ${identifier}`,
      )
    identifiers.set(identifier, locale)
  }

  return { packageName, locales, identifiers }
}

const renderIndex = ({ packageName, locales }) => {
  const lines = [
    '/*',
    '  Autogenerated by rels-i18n offline generate.',
    '  Any changes you make will be overwritten by update or generate.',
    '*/',
    '',
    "import RelsI18n from 'rels-i18n'",
  ]

  for (const { locale } of locales) {
    lines.push(`import ${localeIdentifier(locale)} from './${locale}'`)
  }
  lines.push('')
  for (const { locale } of locales) {
    lines.push(`RelsI18n.addLocaleData(${localeIdentifier(locale)})`)
  }
  lines.push(
    '',
    'const i18n = {',
    "  configure({ locale = 'en' }) {",
    '    RelsI18n.setLocale(locale)',
    '  },',
    '',
    '  t(key, options) {',
    `    return RelsI18n.t('${packageName}.' + key, options)`,
    '  },',
    '',
    '  strftime(date, format) {',
    '    return RelsI18n.strftime(date, format)',
    '  },',
    '',
    '  strftimeWithoutTimezone(date, format) {',
    '    return RelsI18n.strftimeWithoutTimezone(date, format)',
    '  },',
    '}',
    '',
    'export default i18n',
    '',
  )

  return lines.join('\n')
}

const generate = ({ checkOnly = false } = {}) => {
  const project = loadProject()
  const output = renderIndex(project)

  if (checkOnly) {
    const current = fs.existsSync(INDEX_PATH) ? fs.readFileSync(INDEX_PATH, 'utf8') : ''
    if (current !== output)
      throw new Error(
        `${path.relative(PROJECT_ROOT, INDEX_PATH)} is out of date; run rels-i18n generate`,
      )
    return 'rels-i18n check passed: locale data and generated index are current.'
  }

  fs.writeFileSync(INDEX_PATH, output)
  return `rels-i18n generated ${path.relative(PROJECT_ROOT, INDEX_PATH)}`
}

if (require.main === module) {
  const command = process.argv[2]
  try {
    if (command === 'check') console.log(generate({ checkOnly: true }))
    else if (command === 'generate') console.log(generate())
    else
      throw new Error(`Unsupported offline command '${command || ''}'. Expected check or generate.`)
  } catch (error) {
    console.error(`rels-i18n: ${error.message}`)
    process.exitCode = 1
  }
}

module.exports = { generate, localeIdentifier, renderIndex }
